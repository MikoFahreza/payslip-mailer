import crypto from "crypto";

const ALGORITHM = "aes-256-gcm";
const IV_LENGTH = 12; // Standard 96-bit IV for AES-GCM

/**
 * Resolves the 32-byte encryption key from environment variable TOKEN_ENCRYPTION_KEY.
 * Accepts either 32-byte Base64 string or 32-character raw string.
 */
function getEncryptionKey(): Buffer {
  const rawKey = process.env.TOKEN_ENCRYPTION_KEY;
  if (!rawKey) {
    throw new Error(
      "TOKEN_ENCRYPTION_KEY belum dikonfigurasi. Harap tentukan kunci enkripsi 32-byte di environment."
    );
  }

  // Try decoding as base64 first
  const base64Buffer = Buffer.from(rawKey, "base64");
  if (base64Buffer.length === 32) {
    return base64Buffer;
  }

  // If raw string is 32 bytes
  const utf8Buffer = Buffer.from(rawKey, "utf8");
  if (utf8Buffer.length === 32) {
    return utf8Buffer;
  }

  throw new Error(
    `Panjang TOKEN_ENCRYPTION_KEY tidak valid (${base64Buffer.length} bytes terdeteksi). Harus tepat 32 bytes (256-bit).`
  );
}

/**
 * Encrypts a plaintext string using AES-256-GCM with a unique, cryptographically random IV per value.
 * Output format: `<iv_hex>:<auth_tag_hex>:<ciphertext_hex>`
 */
export function encrypt(plaintext: string): string {
  if (typeof plaintext !== "string") {
    throw new Error("Plaintext harus berupa string.");
  }

  const key = getEncryptionKey();
  const iv = crypto.randomBytes(IV_LENGTH);

  const cipher = crypto.createCipheriv(ALGORITHM, key, iv);
  const encrypted = Buffer.concat([cipher.update(plaintext, "utf8"), cipher.final()]);
  const authTag = cipher.getAuthTag();

  return `${iv.toString("hex")}:${authTag.toString("hex")}:${encrypted.toString("hex")}`;
}

/**
 * Decrypts an encrypted string previously generated by `encrypt()`.
 * Verifies authenticity using the GCM authentication tag.
 * Throws an Error if ciphertext or tag has been tampered with.
 */
export function decrypt(encryptedData: string): string {
  if (!encryptedData || typeof encryptedData !== "string") {
    throw new Error("Data terenkripsi tidak valid.");
  }

  const parts = encryptedData.split(":");
  if (parts.length !== 3) {
    throw new Error("Format data terenkripsi tidak valid. Harus 'iv:authTag:ciphertext'.");
  }

  const [ivHex, authTagHex, ciphertextHex] = parts;
  const iv = Buffer.from(ivHex, "hex");
  const authTag = Buffer.from(authTagHex, "hex");
  const ciphertext = Buffer.from(ciphertextHex, "hex");

  if (iv.length !== IV_LENGTH) {
    throw new Error("Panjang IV terenkripsi tidak valid.");
  }

  if (authTag.length !== 16) {
    throw new Error("Panjang Auth Tag terenkripsi tidak valid.");
  }

  const key = getEncryptionKey();
  const decipher = crypto.createDecipheriv(ALGORITHM, key, iv);
  decipher.setAuthTag(authTag);

  try {
    const decrypted = Buffer.concat([decipher.update(ciphertext), decipher.final()]);
    return decrypted.toString("utf8");
  } catch {
    throw new Error("Gagal mendekripsi data: data rusak, kunci salah, atau telah dimanipulasi.");
  }
}
